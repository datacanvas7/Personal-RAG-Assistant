"""Where uploaded files are kept.

``FileStorage`` is the seam for swapping the local volume for S3 or similar later. Stored
names are generated here (``<user_id>/<document_id><extension>``); the client's file name
never reaches the filesystem.
"""

import asyncio
import contextlib
import os
import uuid
from pathlib import Path
from typing import Protocol


class FileStorage(Protocol):
    async def save(
        self, *, user_id: uuid.UUID, document_id: uuid.UUID, extension: str, data: bytes
    ) -> str:
        """Store ``data`` and return its path relative to the storage root."""
        ...

    async def delete(self, relative_path: str) -> None:
        """Remove a stored file; a file that is already gone is not an error."""
        ...

    def resolve(self, relative_path: str) -> Path:
        """The real path of a stored file, for readers that need one (the worker)."""
        ...


class LocalFileStorage:
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()

    async def save(
        self, *, user_id: uuid.UUID, document_id: uuid.UUID, extension: str, data: bytes
    ) -> str:
        relative = f"{user_id}/{document_id}{extension}"
        await asyncio.to_thread(self._write, relative, data)
        return relative

    def _write(self, relative: str, data: bytes) -> None:
        destination = self.resolve(relative)
        destination.parent.mkdir(parents=True, exist_ok=True)
        # Write next to the destination, then rename: readers never see a half-written
        # file, and a crash leaves at most a stray ".tmp" file.
        temporary = destination.with_name(destination.name + ".tmp")
        try:
            with temporary.open("wb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
            temporary.replace(destination)
        except BaseException:
            with contextlib.suppress(OSError):
                temporary.unlink()
            raise

    async def delete(self, relative_path: str) -> None:
        await asyncio.to_thread(self.resolve(relative_path).unlink, missing_ok=True)

    def resolve(self, relative_path: str) -> Path:
        path = (self._root / relative_path).resolve()
        # Defence in depth: stored paths are generated by this class, but a corrupted or
        # tampered database row must still not be able to point outside the root.
        if not path.is_relative_to(self._root):
            raise ValueError("path escapes the storage root")
        return path
